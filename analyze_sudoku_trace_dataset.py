#!/usr/bin/env python3
"""
Analyze Sudoku Trace Dataset

This script demonstrates advanced analysis of the comprehensive Sudoku trace dataset
generated by build_sudoku_trace_dataset.py. It provides tools for understanding
how the HRM model approaches different types of Sudoku problems.

Features:
- Load dataset from local files or Comet ML
- Analyze problem-specific traces
- Compare traces across different problem types
- Identify reasoning patterns
- Visualize state evolution
"""

import torch
import json
import numpy as np
import matplotlib.pyplot as plt
from pathlib import Path
from typing import Dict, List, Any, Tuple, Optional
import argparse
from dataclasses import dataclass
from collections import defaultdict

from hrm_state_recorder import HRMStateRecorder


@dataclass
class TraceAnalysis:
    """Results of analyzing a single trace."""
    problem_id: int
    sudoku_input: List[List[int]]
    sudoku_target: List[List[int]]
    steps_taken: int
    halted: bool
    # Correctness metrics
    is_correct: bool
    accuracy: float
    valid_sudoku: bool
    # State analysis
    h_dimensionality: float
    l_dimensionality: float
    average_halt_confidence: float
    state_evolution_pattern: str  # "stable", "oscillating", "diverging"


def load_dataset_metadata(dataset_dir: str) -> Dict[str, Any]:
    """Load dataset metadata from local directory."""
    metadata_file = Path(dataset_dir) / "dataset_metadata.json"
    
    if not metadata_file.exists():
        raise FileNotFoundError(f"Dataset metadata not found: {metadata_file}")
    
    with open(metadata_file, 'r') as f:
        metadata = json.load(f)
    
    print(f"📊 Dataset Overview:")
    print(f"   Total problems: {metadata['total_problems']}")
    print(f"   Successful traces: {metadata['successful_traces']}")
    print(f"   Success rate: {metadata['successful_traces']/metadata['total_problems']*100:.1f}%")
    
    return metadata


def load_trace_tensors(trace_file: str) -> Dict[str, torch.Tensor]:
    """Load tensor data for a specific trace."""
    trace_path = Path(trace_file)
    
    if trace_path.suffix == '.pt':
        return torch.load(trace_file, map_location="cpu")
    elif trace_path.suffix == '.npz':
        npz_data = np.load(trace_file)
        return {key: torch.from_numpy(npz_data[key]) for key in npz_data.keys()}
    else:
        raise ValueError(f"Unsupported trace file format: {trace_path.suffix}")


def calculate_participation_ratio(states: torch.Tensor) -> float:
    """Calculate participation ratio as measure of effective dimensionality."""
    # Flatten spatial dimensions
    states_flat = states.flatten(start_dim=0, end_dim=-2)  # [num_samples, hidden_size]
    
    # Center the data
    states_centered = states_flat - states_flat.mean(dim=0)
    
    # Compute covariance matrix
    cov = states_centered.T @ states_centered / (states_centered.shape[0] - 1)
    
    # Get eigenvalues
    eigenvals = torch.linalg.eigvals(cov).real
    eigenvals = eigenvals[eigenvals > 1e-8]  # Remove numerical zeros
    
    # Calculate participation ratio
    if len(eigenvals) > 0:
        pr = (eigenvals.sum() ** 2) / (eigenvals ** 2).sum()
        return pr.item()
    else:
        return 0.0


def analyze_state_evolution(h_states: torch.Tensor, l_states: torch.Tensor) -> str:
    """Analyze the pattern of state evolution over time."""
    # Calculate norms over time
    h_norms = h_states.norm(dim=-1).mean(dim=(1,2))  # [num_steps]
    l_norms = l_states.norm(dim=-1).mean(dim=(1,2))  # [num_steps]
    
    # Calculate relative change
    if len(h_norms) > 1:
        h_change = torch.abs(h_norms[1:] - h_norms[:-1]).mean()
        l_change = torch.abs(l_norms[1:] - l_norms[:-1]).mean()
        
        # Classify pattern
        total_change = h_change + l_change
        if total_change < 0.1:
            return "stable"
        elif total_change > 1.0:
            return "diverging" 
        else:
            return "oscillating"
    else:
        return "insufficient_data"


def analyze_single_trace(problem_data: Dict[str, Any], dataset_dir: str) -> Optional[TraceAnalysis]:
    """Analyze a single problem trace."""
    problem_id = problem_data['problem_id']
    sudoku_input = problem_data['sudoku_input'] 
    sudoku_target = problem_data['sudoku_target']
    metadata = problem_data['metadata']
    trace_file = problem_data['trace_file']
    
    # Load trace tensors
    trace_path = Path(dataset_dir) / "traces" / Path(trace_file).name
    if not trace_path.exists():
        # Try alternative naming
        trace_path = Path(dataset_dir) / "traces" / f"trace_{problem_id:06d}_trace_0.pt"
    
    if not trace_path.exists():
        print(f"⚠️  Trace file not found for problem {problem_id}: {trace_path}")
        return None
    
    try:
        tensor_data = load_trace_tensors(str(trace_path))
        
        h_states = tensor_data.get('h_states')  # [steps, batch, seq, hidden]
        l_states = tensor_data.get('l_states')  # [steps, batch, seq, hidden]
        q_halt = tensor_data.get('q_halt_logits')  # [steps, batch]
        q_continue = tensor_data.get('q_continue_logits')  # [steps, batch]
        
        # Calculate metrics
        h_dimensionality = calculate_participation_ratio(h_states) if h_states is not None else 0.0
        l_dimensionality = calculate_participation_ratio(l_states) if l_states is not None else 0.0
        
        # Calculate average halt confidence
        halt_confidence = 0.0
        if q_halt is not None and q_continue is not None:
            halt_probs = torch.sigmoid(q_halt)
            continue_probs = torch.sigmoid(q_continue)
            confidence = torch.abs(halt_probs - continue_probs)
            halt_confidence = confidence.mean().item()
        
        # Analyze evolution pattern
        evolution_pattern = analyze_state_evolution(h_states, l_states) if h_states is not None else "unknown"
        
        return TraceAnalysis(
            problem_id=problem_id,
            sudoku_input=sudoku_input,
            sudoku_target=sudoku_target,
            steps_taken=metadata.get('steps_taken', 0),
            halted=metadata.get('halted', False),
            # Correctness metrics
            is_correct=metadata.get('is_correct', False),
            accuracy=metadata.get('accuracy', 0.0),
            valid_sudoku=metadata.get('valid_sudoku', False),
            # State analysis
            h_dimensionality=h_dimensionality,
            l_dimensionality=l_dimensionality,
            average_halt_confidence=halt_confidence,
            state_evolution_pattern=evolution_pattern
        )
        
    except Exception as e:
        print(f"⚠️  Error analyzing problem {problem_id}: {e}")
        return None


def categorize_sudoku_difficulty(sudoku_input: List[List[int]]) -> str:
    """Categorize Sudoku difficulty based on number of given clues."""
    num_clues = sum(1 for row in sudoku_input for cell in row if cell != 0)
    
    if num_clues >= 30:
        return "easy"
    elif num_clues >= 25:
        return "medium"
    elif num_clues >= 20:
        return "hard"
    else:
        return "extreme"


def analyze_by_difficulty(analyses: List[TraceAnalysis]) -> Dict[str, Dict[str, float]]:
    """Analyze traces grouped by Sudoku difficulty."""
    difficulty_groups = defaultdict(list)
    
    for analysis in analyses:
        if analysis:
            difficulty = categorize_sudoku_difficulty(analysis.sudoku_input)
            difficulty_groups[difficulty].append(analysis)
    
    results = {}
    for difficulty, group in difficulty_groups.items():
        if group:
            results[difficulty] = {
                "count": len(group),
                "success_rate": sum(1 for a in group if a.halted) / len(group),
                "correctness_rate": sum(1 for a in group if a.is_correct) / len(group),
                "valid_sudoku_rate": sum(1 for a in group if a.valid_sudoku) / len(group),
                "avg_accuracy": np.mean([a.accuracy for a in group]),
                "avg_steps": np.mean([a.steps_taken for a in group]),
                "avg_h_dimensionality": np.mean([a.h_dimensionality for a in group]),
                "avg_l_dimensionality": np.mean([a.l_dimensionality for a in group]),
                "avg_halt_confidence": np.mean([a.average_halt_confidence for a in group])
            }
    
    return results


def analyze_reasoning_patterns(analyses: List[TraceAnalysis]) -> Dict[str, Any]:
    """Analyze reasoning patterns across traces."""
    valid_analyses = [a for a in analyses if a is not None]
    
    if not valid_analyses:
        return {}
    
    # Pattern distribution
    patterns = [a.state_evolution_pattern for a in valid_analyses]
    pattern_counts = {p: patterns.count(p) for p in set(patterns)}
    
    # Success analysis by pattern
    pattern_success = {}
    for pattern in set(patterns):
        pattern_traces = [a for a in valid_analyses if a.state_evolution_pattern == pattern]
        if pattern_traces:
            pattern_success[pattern] = {
                "count": len(pattern_traces),
                "success_rate": sum(1 for a in pattern_traces if a.halted) / len(pattern_traces),
                "avg_steps": np.mean([a.steps_taken for a in pattern_traces])
            }
    
    # Dimensionality analysis
    h_dims = [a.h_dimensionality for a in valid_analyses]
    l_dims = [a.l_dimensionality for a in valid_analyses]
    
    return {
        "total_analyzed": len(valid_analyses),
        "pattern_distribution": pattern_counts,
        "pattern_success_rates": pattern_success,
        "dimensionality_stats": {
            "h_mean": np.mean(h_dims),
            "h_std": np.std(h_dims),
            "l_mean": np.mean(l_dims),
            "l_std": np.std(l_dims),
            "h_l_ratio": np.mean(h_dims) / np.mean(l_dims) if np.mean(l_dims) > 0 else 0
        }
    }


def visualize_analysis_results(difficulty_analysis: Dict[str, Dict[str, float]], 
                              reasoning_patterns: Dict[str, Any],
                              output_dir: str = "./analysis_plots"):
    """Create visualizations of the analysis results."""
    output_path = Path(output_dir)
    output_path.mkdir(exist_ok=True)
    
    # Plot 1: Success rate by difficulty
    if difficulty_analysis:
        difficulties = list(difficulty_analysis.keys())
        success_rates = [difficulty_analysis[d]["success_rate"] for d in difficulties]
        avg_steps = [difficulty_analysis[d]["avg_steps"] for d in difficulties]
        
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 5))
        
        # Success rates
        ax1.bar(difficulties, success_rates, color='skyblue')
        ax1.set_title('Success Rate by Sudoku Difficulty')
        ax1.set_ylabel('Success Rate')
        ax1.set_ylim(0, 1)
        
        # Average steps
        ax2.bar(difficulties, avg_steps, color='lightcoral')
        ax2.set_title('Average Steps by Sudoku Difficulty')
        ax2.set_ylabel('Average Steps')
        
        plt.tight_layout()
        plt.savefig(output_path / "difficulty_analysis.png", dpi=150, bbox_inches='tight')
        plt.close()
    
    # Plot 2: Reasoning patterns
    if reasoning_patterns.get("pattern_distribution"):
        patterns = list(reasoning_patterns["pattern_distribution"].keys())
        counts = list(reasoning_patterns["pattern_distribution"].values())
        
        plt.figure(figsize=(10, 6))
        plt.bar(patterns, counts, color='lightgreen')
        plt.title('Distribution of State Evolution Patterns')
        plt.ylabel('Number of Traces')
        plt.xticks(rotation=45)
        plt.tight_layout()
        plt.savefig(output_path / "reasoning_patterns.png", dpi=150, bbox_inches='tight')
        plt.close()
    
    # Plot 3: Dimensionality comparison
    if reasoning_patterns.get("dimensionality_stats"):
        dim_stats = reasoning_patterns["dimensionality_stats"]
        
        plt.figure(figsize=(8, 6))
        modules = ['H-module', 'L-module']
        means = [dim_stats["h_mean"], dim_stats["l_mean"]]
        stds = [dim_stats["h_std"], dim_stats["l_std"]]
        
        plt.bar(modules, means, yerr=stds, capsize=5, color=['blue', 'red'], alpha=0.7)
        plt.title('Average Dimensionality by Module')
        plt.ylabel('Participation Ratio')
        plt.tight_layout()
        plt.savefig(output_path / "dimensionality_comparison.png", dpi=150, bbox_inches='tight')
        plt.close()
    
    print(f"📈 Visualizations saved to: {output_path}")


def main():
    """Main analysis function."""
    parser = argparse.ArgumentParser(description="Analyze Sudoku trace dataset")
    parser.add_argument("--dataset-dir", 
                       default="./sudoku_trace_dataset",
                       help="Path to dataset directory")
    parser.add_argument("--max-traces", type=int, default=None,
                       help="Maximum number of traces to analyze")
    parser.add_argument("--output-dir", 
                       default="./analysis_results",
                       help="Output directory for analysis results")
    parser.add_argument("--visualize", action="store_true",
                       help="Create visualization plots")
    parser.add_argument("--save-results", action="store_true",
                       help="Save analysis results to JSON")
    
    args = parser.parse_args()
    
    dataset_dir = Path(args.dataset_dir)
    if not dataset_dir.exists():
        print(f"❌ Dataset directory not found: {dataset_dir}")
        print("   Run build_sudoku_trace_dataset.py first")
        return 1
    
    try:
        # Load dataset metadata
        print("📊 Loading dataset...")
        metadata = load_dataset_metadata(str(dataset_dir))
        
        # Analyze traces
        print(f"\n🔍 Analyzing traces...")
        analyses = []
        problems = metadata["problems"]
        
        if args.max_traces:
            problems = problems[:args.max_traces]
        
        for i, problem_data in enumerate(problems):
            if i % 50 == 0:
                print(f"   Processed {i}/{len(problems)} traces...")
            
            analysis = analyze_single_trace(problem_data, str(dataset_dir))
            analyses.append(analysis)
        
        valid_analyses = [a for a in analyses if a is not None]
        print(f"✅ Successfully analyzed {len(valid_analyses)}/{len(problems)} traces")
        
        # Perform analysis
        print(f"\n📈 Performing analysis...")
        
        # Difficulty analysis
        difficulty_results = analyze_by_difficulty(valid_analyses)
        print(f"\n🎯 Analysis by Difficulty:")
        for difficulty, stats in difficulty_results.items():
            print(f"   {difficulty.title()}: {stats['count']} problems")
            print(f"      Halting rate: {stats['success_rate']:.1%}")
            print(f"      Correctness rate: {stats['correctness_rate']:.1%}")
            print(f"      Valid Sudoku rate: {stats['valid_sudoku_rate']:.1%}")
            print(f"      Avg accuracy: {stats['avg_accuracy']:.1%}")
            print(f"      Avg steps: {stats['avg_steps']:.1f}")
            print()
        
        # Reasoning patterns
        reasoning_results = analyze_reasoning_patterns(valid_analyses)
        print(f"\n🧠 Reasoning Patterns:")
        print(f"   Total analyzed: {reasoning_results['total_analyzed']}")
        for pattern, info in reasoning_results.get("pattern_success_rates", {}).items():
            print(f"   {pattern}: {info['count']} traces, {info['success_rate']:.1%} success")
        
        # Dimensionality insights
        dim_stats = reasoning_results.get("dimensionality_stats", {})
        if dim_stats:
            print(f"\n📐 Dimensionality Analysis:")
            print(f"   H-module: {dim_stats['h_mean']:.1f} ± {dim_stats['h_std']:.1f}")
            print(f"   L-module: {dim_stats['l_mean']:.1f} ± {dim_stats['l_std']:.1f}")
            print(f"   H/L ratio: {dim_stats['h_l_ratio']:.2f}")
        
        # Save results
        if args.save_results:
            results = {
                "difficulty_analysis": difficulty_results,
                "reasoning_patterns": reasoning_results,
                "dataset_info": {
                    "total_problems": len(problems),
                    "analyzed_problems": len(valid_analyses),
                    "dataset_path": str(dataset_dir)
                }
            }
            
            output_dir = Path(args.output_dir)
            output_dir.mkdir(exist_ok=True)
            
            results_file = output_dir / "analysis_results.json"
            with open(results_file, 'w') as f:
                json.dump(results, f, indent=2)
            print(f"\n💾 Results saved to: {results_file}")
        
        # Create visualizations
        if args.visualize:
            visualize_analysis_results(difficulty_results, reasoning_results, args.output_dir)
        
        print(f"\n🎉 Analysis completed!")
        return 0
        
    except Exception as e:
        print(f"❌ Analysis failed: {e}")
        import traceback
        traceback.print_exc()
        return 1


if __name__ == "__main__":
    exit(main()) 